/// An inclusive version range. `min > max` encodes the empty range.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
struct VersionRange {
    min: i16,
    max: i16, // i16::MAX means open-ended
}

impl VersionRange {
    const EMPTY: VersionRange = VersionRange { min: 1, max: 0 };

    fn parse(s: &str) -> Result<VersionRange> {
        let s = s.trim();
        if s == "none" {
            return Ok(VersionRange::EMPTY);
        }
        if let Some(min) = s.strip_suffix('+') {
            return Ok(VersionRange {
                min: min.parse()?,
                max: i16::MAX,
            });
        }
        if let Some((min, max)) = s.split_once('-') {
            return Ok(VersionRange {
                min: min.parse()?,
                max: max.parse()?,
            });
        }
        let v: i16 = s.parse()?;
        Ok(VersionRange { min: v, max: v })
    }

    fn is_empty(self) -> bool {
        self.min > self.max
    }

    /// The versions in both ranges.
    fn intersect(self, other: VersionRange) -> VersionRange {
        VersionRange {
            min: self.min.max(other.min),
            max: self.max.min(other.max),
        }
    }

    /// Rust boolean expression testing membership of `version`, folding to
    /// `true`/`false` where the outcome is constant over `valid`.
    fn expr(self, valid: VersionRange) -> String {
        if self.is_empty() {
            return "false".into();
        }
        let lower = self.min > valid.min; // lower bound can exclude some valid version
        let upper = self.max < valid.max; // upper bound can exclude some valid version
        match (lower, upper) {
            (false, false) => "true".into(),
            (true, false) => format!("version >= {}", self.min),
            (false, true) => format!("version <= {}", self.max),
            (true, true) if self.min == self.max => format!("version == {}", self.min),
            (true, true) => format!("({}..={}).contains(&version)", self.min, self.max),
        }
    }
}

#[derive(Debug, Clone)]
enum FieldType {
    Bool,
    Int8,
    Int16,
    Uint16,
    Int32,
    Uint32,
    Int64,
    Float64,
    Uuid,
    String,
    Bytes,
    Records,
    Struct(String),
    Array(Box<FieldType>),
}

impl FieldType {
    fn parse(s: &str) -> Result<FieldType> {
        if let Some(elem) = s.strip_prefix("[]") {
            return Ok(FieldType::Array(Box::new(FieldType::parse(elem)?)));
        }
        Ok(match s {
            "bool" => FieldType::Bool,
            "int8" => FieldType::Int8,
            "int16" => FieldType::Int16,
            "uint16" => FieldType::Uint16,
            "int32" => FieldType::Int32,
            "uint32" => FieldType::Uint32,
            "int64" => FieldType::Int64,
            "float64" => FieldType::Float64,
            "uuid" => FieldType::Uuid,
            "string" => FieldType::String,
            "bytes" => FieldType::Bytes,
            "records" => FieldType::Records,
            name if name.chars().next().is_some_and(|c| c.is_ascii_uppercase()) => {
                FieldType::Struct(name.to_owned())
            }
            other => bail!("unsupported field type {other:?}"),
        })
    }
}

#[derive(Debug, Clone)]
struct Field {
    name: String,
    ftype: FieldType,
    versions: VersionRange,
    nullable: Option<VersionRange>,
    tag: Option<u64>,
    tagged_versions: Option<VersionRange>,
    default: Option<Value>,
    flexible_override: Option<VersionRange>,
    about: Option<String>,
    inline_fields: Option<Vec<Field>>,
}

#[derive(Debug)]
struct StructDef {
    name: String,
    fields: Vec<Field>,
}

#[derive(Debug)]
struct Message {
    name: String,
    typ: String, // request | response | header | data
    api_key: Option<i16>,
    valid: VersionRange,
    flexible: VersionRange,
    fields: Vec<Field>,
    common_structs: Vec<StructDef>,
    schema_file: String,
}

fn parse_message(path: &Path) -> Result<Message> {
    let raw = fs::read_to_string(path)?;
    let stripped: String = raw
        .lines()
        .filter(|line| !line.trim_start().starts_with("//"))
        .collect::<Vec<_>>()
        .join("\n");
    let json: Value = serde_json::from_str(&stripped)?;

    let name = json["name"].as_str().context("missing name")?.to_owned();
    let typ = json["type"].as_str().context("missing type")?.to_owned();
    let api_key = json["apiKey"].as_i64().map(|k| k as i16);
    let valid = VersionRange::parse(
        json["validVersions"]
            .as_str()
            .context("missing validVersions")?,
    )?;
    let flexible = match json["flexibleVersions"].as_str() {
        Some(s) => VersionRange::parse(s)?,
        None => VersionRange::EMPTY,
    };
    let fields = parse_fields(json["fields"].as_array().context("missing fields")?)?;
    let common_structs = match json["commonStructs"].as_array() {
        Some(defs) => defs
            .iter()
            .map(|d| {
                Ok(StructDef {
                    name: d["name"].as_str().context("commonStruct name")?.to_owned(),
                    fields: parse_fields(d["fields"].as_array().context("commonStruct fields")?)?,
                })
            })
            .collect::<Result<Vec<_>>>()?,
        None => Vec::new(),
    };
    Ok(Message {
        name,
        typ,
        api_key,
        valid,
        flexible,
        fields,
        common_structs,
        schema_file: path.file_name().unwrap().to_string_lossy().into_owned(),
    })
}

fn parse_fields(fields: &[Value]) -> Result<Vec<Field>> {
    fields
        .iter()
        .map(|f| {
            let name = f["name"].as_str().context("field name")?.to_owned();
            let ftype = FieldType::parse(f["type"].as_str().context("field type")?)
                .with_context(|| format!("field {name}"))?;
            let versions = VersionRange::parse(f["versions"].as_str().context("field versions")?)?;
            let nullable = match f["nullableVersions"].as_str() {
                Some(s) => Some(VersionRange::parse(s)?),
                None => None,
            };
            let flexible_override = match f["flexibleVersions"].as_str() {
                Some(s) => Some(VersionRange::parse(s)?),
                None => None,
            };
            let inline_fields = match f["fields"].as_array() {
                Some(inner) => Some(parse_fields(inner)?),
                None => None,
            };
            let tagged_versions = match f["taggedVersions"].as_str() {
                Some(s) => Some(VersionRange::parse(s)?),
                None => None,
            };
            Ok(Field {
                name,
                ftype,
                versions,
                nullable,
                tag: f["tag"].as_u64(),
                tagged_versions,
                default: f.get("default").cloned(),
                flexible_override,
                about: f["about"].as_str().map(str::to_owned),
                inline_fields,
            })
        })
        .collect()
}

