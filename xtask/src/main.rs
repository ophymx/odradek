// Code generation
// ---------------------------------------------------------------------------

fn generate_message(msg: &Message) -> Result<String> {
    let mut structs: Vec<StructDef> = vec![StructDef {
        name: msg.name.clone(),
        fields: msg.fields.clone(),
    }];
    collect_inline_structs(&msg.fields, &mut structs);
    for cs in &msg.common_structs {
        if !structs.iter().any(|s| s.name == cs.name) {
            structs.push(StructDef {
                name: cs.name.clone(),
                fields: cs.fields.clone(),
            });
        }
        collect_inline_structs(&cs.fields, &mut structs);
    }

    // The generator only handles the shape every current schema uses: a
    // tagged field is tagged for its entire lifetime. A field that is
    // wire-encoded in some versions and tagged in others needs new
    // codegen support — fail loudly rather than mis-encode.
    let mut has_tagged = false;
    for def in &structs {
        for f in &def.fields {
            if f.tag.is_some() {
                has_tagged = true;
                if f.tagged_versions != Some(f.versions) {
                    bail!(
                        "{}.{}: taggedVersions {:?} != versions {:?}; \
                         partially tagged fields are not supported",
                        def.name,
                        f.name,
                        f.tagged_versions,
                        f.versions
                    );
                }
            }
        }
    }

    let mut out = String::new();
    let w = &mut out;
    let _ = writeln!(
        w,
        "//! `{}` — generated from `schemas/{}`.",
        msg.name, msg.schema_file
    );
    let _ = writeln!(w, "//!");
    let _ = writeln!(
        w,
        "//! @generated by `cargo xtask codegen`. Do not edit by hand."
    );
    if has_tagged {
        let _ = writeln!(w, "//!");
        let _ = writeln!(
            w,
            "//! Tagged fields are materialized as `Option` struct fields \
             (`None` = absent\n//! on the wire); unknown tags still round-trip \
             through `unknown_tagged_fields`."
        );
    }
    let _ = writeln!(w);
    // Style lints that the generated encode/decode shapes trip by design:
    // decode fills a Default-initialized struct, version guards produce
    // negations like `!(version >= 3)`, and tagged-field snippets reuse
    // the by-reference path `(*v)` uniformly across value shapes.
    let _ = writeln!(
        w,
        "#![allow(clippy::field_reassign_with_default, clippy::nonminimal_bool, clippy::derivable_impls, clippy::borrow_deref_ref, clippy::double_parens, unused_parens)]"
    );
    let _ = writeln!(w);
    let _ = writeln!(w, "use bytes::{{Buf, BufMut}};");
    let _ = writeln!(w);
    let _ = writeln!(w, "use crate::budget::{{Budget, Limits}};");
    let _ = writeln!(w, "#[allow(unused_imports)]");
    let _ = writeln!(w, "use crate::error::{{DecodeError, EncodeError}};");
    let _ = writeln!(w, "use crate::wire::{{self, RawTaggedField}};");
    let _ = writeln!(w);
    let _ = writeln!(
        w,
        "/// Whether `version` of this message uses the flexible (compact) encoding."
    );
    let _ = writeln!(w, "pub fn is_flexible(version: i16) -> bool {{");
    let _ = writeln!(w, "    let _ = version;");
    let _ = writeln!(w, "    {}", msg.flexible.expr(msg.valid));
    let _ = writeln!(w, "}}");

    for (i, def) in structs.iter().enumerate() {
        generate_struct(w, msg, def, i == 0)?;
    }
    Ok(out)
}

fn collect_inline_structs(fields: &[Field], out: &mut Vec<StructDef>) {
    for f in fields {
        if let Some(inner) = &f.inline_fields {
            let name = struct_name_of(&f.ftype);
            if let Some(name) = name {
                if !out.iter().any(|s| s.name == name) {
                    out.push(StructDef {
                        name: name.to_owned(),
                        fields: inner.clone(),
                    });
                }
            }
            collect_inline_structs(inner, out);
        }
    }
}

fn struct_name_of(ftype: &FieldType) -> Option<&str> {
    match ftype {
        FieldType::Struct(n) => Some(n),
        FieldType::Array(inner) => struct_name_of(inner),
        _ => None,
    }
}

fn generate_struct(w: &mut String, msg: &Message, def: &StructDef, is_top: bool) -> Result<()> {
    let wire_fields: Vec<&Field> = def.fields.iter().filter(|f| f.tag.is_none()).collect();
    let mut tagged_fields: Vec<&Field> = def.fields.iter().filter(|f| f.tag.is_some()).collect();
    tagged_fields.sort_by_key(|f| f.tag);

    let _ = writeln!(w);
    if is_top {
        let _ = writeln!(w, "/// `{}`, versions {}.", def.name, range_doc(msg.valid));
    } else {
        let _ = writeln!(w, "/// `{}` (nested in [`{}`]).", def.name, msg.name);
    }
    let _ = writeln!(w, "#[derive(Debug, Clone, PartialEq)]");
    let _ = writeln!(w, "#[non_exhaustive]");
    let _ = writeln!(w, "pub struct {} {{", def.name);
    for f in &wire_fields {
        if let Some(about) = &f.about {
            let _ = writeln!(
                w,
                "    /// {}",
                about.replace('[', "\\[").replace(']', "\\]")
            );
        }
        let _ = writeln!(w, "    pub {}: {},", rust_field_name(&f.name), rust_type(f));
    }
    for f in &tagged_fields {
        if let Some(about) = &f.about {
            let _ = writeln!(
                w,
                "    /// {}",
                about.replace('[', "\\[").replace(']', "\\]")
            );
        }
        let _ = writeln!(
            w,
            "    /// (Tagged field {}; `None` = absent on the wire.)",
            f.tag.unwrap()
        );
        let _ = writeln!(
            w,
            "    pub {}: Option<{}>,",
            rust_field_name(&f.name),
            rust_type(f)
        );
    }
    let _ = writeln!(
        w,
        "    /// Tagged fields not (yet) known to this crate, kept raw."
    );
    let _ = writeln!(w, "    pub unknown_tagged_fields: Vec<RawTaggedField>,");
    let _ = writeln!(w, "}}");

    // Default impl using schema defaults.
    let _ = writeln!(w);
    let _ = writeln!(w, "impl Default for {} {{", def.name);
    let _ = writeln!(w, "    fn default() -> Self {{");
    let _ = writeln!(w, "        Self {{");
    for f in &wire_fields {
        let _ = writeln!(
            w,
            "            {}: {},",
            rust_field_name(&f.name),
            default_expr(f)?
        );
    }
    for f in &tagged_fields {
        let _ = writeln!(w, "            {}: None,", rust_field_name(&f.name));
    }
    let _ = writeln!(w, "            unknown_tagged_fields: Vec::new(),");
    let _ = writeln!(w, "        }}");
    let _ = writeln!(w, "    }}");
    let _ = writeln!(w, "}}");

    let _ = writeln!(w);
    let _ = writeln!(w, "impl {} {{", def.name);
    if is_top {
        if let Some(key) = msg.api_key {
            let _ = writeln!(w, "    /// This message's api key in Kafka's registry.");
            let _ = writeln!(w, "    pub const API_KEY: i16 = {key};");
        }
        let _ = writeln!(
            w,
            "    /// The lowest schema version this snapshot can speak."
        );
        let _ = writeln!(w, "    pub const MIN_VERSION: i16 = {};", msg.valid.min);
        let _ = writeln!(
            w,
            "    /// The highest schema version this snapshot can speak."
        );
        let _ = writeln!(w, "    pub const MAX_VERSION: i16 = {};", msg.valid.max);
        let _ = writeln!(w);
    }

    // encode
    let _ = writeln!(w, "    /// Encode this `{}` at `version`.", def.name);
    let _ = writeln!(
        w,
        "    pub fn encode(&self, buf: &mut impl BufMut, version: i16) -> Result<(), EncodeError> {{"
    );
    for f in &wire_fields {
        let body = encode_field(msg, f)?;
        emit_guarded(w, &f.versions.expr(msg.valid), &body);
    }
    if tagged_fields.is_empty() {
        let _ = writeln!(w, "        if is_flexible(version) {{");
        let _ = writeln!(
            w,
            "            wire::put_tagged_fields(buf, &self.unknown_tagged_fields);"
        );
        let _ = writeln!(w, "        }}");
    } else {
        let _ = writeln!(w, "        if is_flexible(version) {{");
        let _ = writeln!(
            w,
            "            let mut tagged = self.unknown_tagged_fields.clone();"
        );
        for f in &tagged_fields {
            let name = rust_field_name(&f.name);
            let encode = encode_field_value(msg, f, "(*v)")?;
            let mut body = String::new();
            let _ = writeln!(body, "if let Some(v) = &self.{name} {{");
            let _ = writeln!(body, "    let mut tag_data = bytes::BytesMut::new();");
            let _ = writeln!(body, "    {{");
            let _ = writeln!(body, "        let buf = &mut tag_data;");
            for line in encode.lines() {
                let _ = writeln!(body, "        {line}");
            }
            let _ = writeln!(body, "    }}");
            let _ = writeln!(
                body,
                "    tagged.push(RawTaggedField {{ tag: {}, data: tag_data.freeze() }});",
                f.tag.unwrap()
            );
            let _ = write!(body, "}}");
            let mut guarded = String::new();
            emit_guarded(&mut guarded, &f.versions.expr(msg.valid), &body);
            for line in guarded.lines() {
                let _ = writeln!(w, "    {line}");
            }
        }
        let _ = writeln!(w, "            tagged.sort_by_key(|f| f.tag);");
        let _ = writeln!(w, "            wire::put_tagged_fields(buf, &tagged);");
        let _ = writeln!(w, "        }}");
    }
    let _ = writeln!(w, "        Ok(())");
    let _ = writeln!(w, "    }}");

    // decode: three entry points over one body. `decode` keeps its
    // signature (and gains the default bound), `decode_with_limits`
    // takes a policy, `decode_with_budget` joins a bound already in
    // progress so that nesting cannot multiply it.
    let _ = writeln!(w);
    let _ = writeln!(
        w,
        "    /// Decode one `{}`, bounding allocation by the default\n    \
             /// [`Limits`] derived from `buf`'s remaining length.",
        def.name
    );
    let _ = writeln!(
        w,
        "    pub fn decode(buf: &mut impl Buf, version: i16) -> Result<Self, DecodeError> {{"
    );
    let _ = writeln!(
        w,
        "        Self::decode_with_limits(buf, version, Limits::default())"
    );
    let _ = writeln!(w, "    }}");
    let _ = writeln!(w);
    let _ = writeln!(w, "    /// Decode one `{}` under `limits`.", def.name);
    let _ = writeln!(
        w,
        "    pub fn decode_with_limits(buf: &mut impl Buf, version: i16, limits: Limits) -> Result<Self, DecodeError> {{"
    );
    let _ = writeln!(
        w,
        "        let mut budget = limits.budget(buf.remaining());"
    );
    let _ = writeln!(
        w,
        "        Self::decode_with_budget(buf, version, &mut budget)"
    );
    let _ = writeln!(w, "    }}");
    let _ = writeln!(w);
    let _ = writeln!(
        w,
        "    /// Decode one `{}` against an existing `budget`.",
        def.name
    );
    let _ = writeln!(
        w,
        "    pub fn decode_with_budget(buf: &mut impl Buf, version: i16, budget: &mut Budget) -> Result<Self, DecodeError> {{"
    );
    let _ = writeln!(w, "        let mut this = Self::default();");
    for f in &wire_fields {
        let body = decode_field(msg, f)?;
        emit_guarded(w, &f.versions.expr(msg.valid), &body);
    }
    if tagged_fields.is_empty() {
        let _ = writeln!(w, "        if is_flexible(version) {{");
        let _ = writeln!(
            w,
            "            this.unknown_tagged_fields = wire::get_tagged_fields_with_budget(buf, budget)?;"
        );
        let _ = writeln!(w, "        }}");
    } else {
        let _ = writeln!(w, "        if is_flexible(version) {{");
        let _ = writeln!(
            w,
            "            for raw in wire::get_tagged_fields_with_budget(buf, budget)? {{"
        );
        for (i, f) in tagged_fields.iter().enumerate() {
            let name = rust_field_name(&f.name);
            let value = decode_value(msg, f)?;
            let keyword = if i == 0 { "if" } else { "} else if" };
            let versions = f.versions.expr(msg.valid);
            let guard = if versions == "true" {
                format!("raw.tag == {}", f.tag.unwrap())
            } else {
                format!("raw.tag == {} && ({versions})", f.tag.unwrap())
            };
            let _ = writeln!(w, "                {keyword} {guard} {{");
            let _ = writeln!(w, "                    let mut tag_data = raw.data;");
            let _ = writeln!(w, "                    let buf = &mut tag_data;");
            let mut body = String::new();
            let _ = writeln!(body, "this.{name} = Some({value});");
            let _ = writeln!(
                body,
                "if buf.has_remaining() {{\n    return Err(DecodeError::InvalidLength(\n        i64::try_from(buf.remaining()).unwrap_or(i64::MAX),\n    ));\n}}"
            );
            for line in body.lines() {
                let _ = writeln!(w, "                    {line}");
            }
        }
        let _ = writeln!(w, "                }} else {{");
        let _ = writeln!(
            w,
            "                    budget.push(&mut this.unknown_tagged_fields, raw)?;"
        );
        let _ = writeln!(w, "                }}");
        let _ = writeln!(w, "            }}");
        let _ = writeln!(w, "        }}");
    }
    let _ = writeln!(w, "        Ok(this)");
    let _ = writeln!(w, "    }}");
    let _ = writeln!(w, "}}");

    // The generic spine: every top-level keyed message implements
    // crate::Message by delegating to the inherent methods above.
    if is_top {
        if let Some(key) = msg.api_key {
            let _ = writeln!(w);
            let _ = writeln!(w, "impl crate::Message for {} {{", def.name);
            let _ = writeln!(w, "    const API_KEY: i16 = {key};");
            let _ = writeln!(w, "    const MIN_VERSION: i16 = {};", msg.valid.min);
            let _ = writeln!(w, "    const MAX_VERSION: i16 = {};", msg.valid.max);
            let _ = writeln!(w);
            let _ = writeln!(
                w,
                "    fn encode(&self, buf: &mut impl BufMut, version: i16) -> Result<(), EncodeError> {{"
            );
            let _ = writeln!(w, "        {}::encode(self, buf, version)", def.name);
            let _ = writeln!(w, "    }}");
            let _ = writeln!(
                w,
                "    fn decode(buf: &mut impl Buf, version: i16) -> Result<Self, DecodeError> {{"
            );
            let _ = writeln!(w, "        {}::decode(buf, version)", def.name);
            let _ = writeln!(w, "    }}");
            let _ = writeln!(
                w,
                "    fn decode_with_limits(buf: &mut impl Buf, version: i16, limits: Limits) -> Result<Self, DecodeError> {{"
            );
            let _ = writeln!(
                w,
                "        {}::decode_with_limits(buf, version, limits)",
                def.name
            );
            let _ = writeln!(w, "    }}");
            let _ = writeln!(w, "}}");
        }
    }
    Ok(())
}

/// Emit `body` wrapped in `if guard { .. }`, folding constant guards.
fn emit_guarded(w: &mut String, guard: &str, body: &str) {
    match guard {
        "false" => {}
        "true" => {
            for line in body.lines() {
                let _ = writeln!(w, "        {line}");
            }
        }
        cond => {
            let _ = writeln!(w, "        if {cond} {{");
            for line in body.lines() {
                let _ = writeln!(w, "            {line}");
            }
            let _ = writeln!(w, "        }}");
        }
    }
}

fn range_doc(r: VersionRange) -> String {
    if r.max == i16::MAX {
        format!("{}+", r.min)
    } else {
        format!("{}-{}", r.min, r.max)
    }
}

// --- naming -----------------------------------------------------------------

fn snake_case(name: &str) -> String {
    let mut out = String::new();
    let chars: Vec<char> = name.chars().collect();
    for (i, &c) in chars.iter().enumerate() {
        if c.is_ascii_uppercase() {
            let prev_lower =
                i > 0 && (chars[i - 1].is_ascii_lowercase() || chars[i - 1].is_ascii_digit());
            let next_lower = i > 0
                && chars[i - 1].is_ascii_uppercase()
                && chars.get(i + 1).is_some_and(|n| n.is_ascii_lowercase());
            if prev_lower || next_lower {
                out.push('_');
            }
            out.push(c.to_ascii_lowercase());
        } else {
            out.push(c);
        }
    }
    out
}

const KEYWORDS: &[&str] = &[
    "as", "async", "await", "box", "break", "const", "continue", "crate", "do", "dyn", "else",
    "enum", "extern", "false", "final", "fn", "for", "if", "impl", "in", "let", "loop", "macro",
    "match", "mod", "move", "mut", "override", "priv", "pub", "ref", "return", "static", "struct",
    "super", "trait", "true", "try", "type", "unsafe", "use", "where", "while", "yield",
];

fn rust_field_name(name: &str) -> String {
    let snake = snake_case(name);
    if KEYWORDS.contains(&snake.as_str()) {
        format!("r#{snake}")
    } else {
        snake
    }
}

// --- types ------------------------------------------------------------------

fn base_rust_type(ftype: &FieldType) -> String {
    match ftype {
        FieldType::Bool => "bool".into(),
        FieldType::Int8 => "i8".into(),
        FieldType::Int16 => "i16".into(),
        FieldType::Uint16 => "u16".into(),
        FieldType::Int32 => "i32".into(),
        FieldType::Uint32 => "u32".into(),
        FieldType::Int64 => "i64".into(),
        FieldType::Float64 => "f64".into(),
        FieldType::Uuid => "[u8; 16]".into(),
        FieldType::String => "String".into(),
        FieldType::Bytes | FieldType::Records => "bytes::Bytes".into(),
        FieldType::Struct(n) => n.clone(),
        FieldType::Array(inner) => format!("Vec<{}>", base_rust_type(inner)),
    }
}

fn rust_type(f: &Field) -> String {
    let base = base_rust_type(&f.ftype);
    if f.nullable.is_some() {
        format!("Option<{base}>")
    } else {
        base
    }
}

// --- defaults ----------------------------------------------------------------

fn default_str(f: &Field) -> Option<String> {
    match &f.default {
        Some(Value::String(s)) => Some(s.clone()),
        Some(Value::Number(n)) => Some(n.to_string()),
        Some(Value::Bool(b)) => Some(b.to_string()),
        _ => None,
    }
}

fn parse_int_default(s: &str) -> Result<i128> {
    let s = s.trim();
    if let Some(hex) = s.strip_prefix("0x") {
        Ok(i128::from_str_radix(hex, 16)?)
    } else if let Some(hex) = s.strip_prefix("-0x") {
        Ok(-i128::from_str_radix(hex, 16)?)
    } else {
        Ok(s.parse()?)
    }
}

fn default_expr(f: &Field) -> Result<String> {
    let dflt = default_str(f);
    let is_null = dflt.as_deref() == Some("null");
    if is_null && f.nullable.is_none() {
        bail!("field {} has default null but no nullableVersions", f.name);
    }
    let inner = match &f.ftype {
        FieldType::Bool => dflt.unwrap_or_else(|| "false".into()),
        FieldType::Int8
        | FieldType::Int16
        | FieldType::Uint16
        | FieldType::Int32
        | FieldType::Uint32
        | FieldType::Int64 => match &dflt {
            Some(s) if !is_null => parse_int_default(s)?.to_string(),
            _ => "0".into(),
        },
        FieldType::Float64 => match &dflt {
            Some(s) if !is_null => format!("{:?}", s.parse::<f64>()?),
            _ => "0.0".into(),
        },
        FieldType::Uuid => "[0u8; 16]".into(),
        FieldType::String => match &dflt {
            Some(s) if !is_null => format!("{s:?}.to_string()"),
            _ => "String::new()".into(),
        },
        FieldType::Bytes | FieldType::Records => "bytes::Bytes::new()".into(),
        FieldType::Struct(_) => "Default::default()".into(),
        FieldType::Array(_) => "Vec::new()".into(),
    };
    Ok(if f.nullable.is_some() {
        if is_null {
            "None".into()
        } else {
            format!("Some({inner})")
        }
    } else {
        inner
    })
}

// --- encode ------------------------------------------------------------------

/// Flexibility test expression for one field (field-level override wins).
fn field_flex_expr(msg: &Message, f: &Field) -> String {
    match f.flexible_override {
        Some(r) => r.expr(msg.valid),
        None => "is_flexible(version)".into(),
    }
}

/// Pick `flex_arm` or `plain_arm` based on the field's flexibility expression,
/// folding constant cases.
fn flex_switch(flex: &str, flex_arm: String, plain_arm: String) -> String {
    match flex {
        "true" => flex_arm,
        "false" => plain_arm,
        cond => format!("if {cond} {{\n    {flex_arm}\n}} else {{\n    {plain_arm}\n}}"),
    }
}

fn encode_field(msg: &Message, f: &Field) -> Result<String> {
    let name = rust_field_name(&f.name);
    encode_field_value(msg, f, &format!("self.{name}"))
}

/// Encode `f` reading its value from `path` (`buf` is the free-variable
/// write target, letting tagged fields shadow it with a side buffer).
fn encode_field_value(msg: &Message, f: &Field, path: &str) -> Result<String> {
    let flex = field_flex_expr(msg, f);
    // Folded over the versions the field is actually on the wire, so
    // a guard that can never fire is not emitted at all.
    let nullable_expr = f.nullable.map(|r| r.expr(msg.valid.intersect(f.versions)));

    let code = match (&f.ftype, &nullable_expr) {
        // Scalars, non-nullable
        (FieldType::Bool, None) => format!("buf.put_u8(u8::from({path}));"),
        (FieldType::Int8, None) => format!("buf.put_i8({path});"),
        (FieldType::Int16, None) => format!("buf.put_i16({path});"),
        (FieldType::Uint16, None) => format!("buf.put_u16({path});"),
        (FieldType::Int32, None) => format!("buf.put_i32({path});"),
        (FieldType::Uint32, None) => format!("buf.put_u32({path});"),
        (FieldType::Int64, None) => format!("buf.put_i64({path});"),
        (FieldType::Float64, None) => format!("buf.put_f64({path});"),
        (FieldType::Uuid, None) => format!("wire::put_uuid(buf, {path});"),
        (FieldType::Struct(_), None) => format!("{path}.encode(buf, version)?;"),
        (FieldType::String, None) => flex_switch(
            &flex,
            format!("wire::put_compact_string(buf, &{path});"),
            format!("wire::put_string(buf, &{path})?;"),
        ),
        (FieldType::Bytes | FieldType::Records, None) => flex_switch(
            &flex,
            format!("wire::put_compact_bytes(buf, &{path});"),
            format!("wire::put_bytes(buf, &{path})?;"),
        ),
        (FieldType::String, Some(nullable)) => {
            let write = flex_switch(
                &flex,
                format!("wire::put_compact_nullable_string(buf, {path}.as_deref());"),
                format!("wire::put_nullable_string(buf, {path}.as_deref())?;"),
            );
            null_guard(&f.name, path, nullable, write)
        }
        (FieldType::Bytes | FieldType::Records, Some(nullable)) => {
            let write = flex_switch(
                &flex,
                format!("wire::put_compact_nullable_bytes(buf, {path}.as_deref());"),
                format!("wire::put_nullable_bytes(buf, {path}.as_deref())?;"),
            );
            null_guard(&f.name, path, nullable, write)
        }
        (FieldType::Array(elem), None) => {
            let put_len = flex_switch(
                &flex,
                format!("wire::put_compact_array_len(buf, Some({path}.len()));"),
                format!("wire::put_array_len(buf, Some({path}.len()))?;"),
            );
            let elem_code = encode_element(msg, f, elem)?;
            format!("{put_len}\nfor item in &{path} {{\n    {elem_code}\n}}")
        }
        (FieldType::Array(elem), Some(nullable)) => {
            let put_some = flex_switch(
                &flex,
                "wire::put_compact_array_len(buf, Some(items.len()));".into(),
                "wire::put_array_len(buf, Some(items.len()))?;".into(),
            );
            let put_none = flex_switch(
                &flex,
                "wire::put_compact_array_len(buf, None);".into(),
                "wire::put_array_len(buf, None)?;".into(),
            );
            let elem_code = encode_element(msg, f, elem)?;
            let none_arm = if nullable == "true" {
                put_none
            } else {
                format!(
                    "if !({nullable}) {{\n    return Err(EncodeError::NullField({:?}));\n}}\n{put_none}",
                    f.name
                )
            };
            format!(
                "match &{path} {{\n    Some(items) => {{\n        {put_some}\n        for item in items {{\n            {elem_code}\n        }}\n    }}\n    None => {{\n        {none_arm}\n    }}\n}}",
            )
        }
        (FieldType::Struct(_), Some(nullable)) => {
            // Kafka serializes a nullable struct as a signed marker
            // byte: -1 for null, 1 followed by the struct's fields.
            let none_arm = if nullable == "true" {
                "buf.put_i8(-1);".to_string()
            } else {
                format!(
                    "if !({nullable}) {{\n    return Err(EncodeError::NullField({:?}));\n}}\nbuf.put_i8(-1);",
                    f.name
                )
            };
            format!(
                "match &{path} {{\n    Some(v) => {{\n        buf.put_i8(1);\n        v.encode(buf, version)?;\n    }}\n    None => {{\n        {none_arm}\n    }}\n}}"
            )
        }
        (other, Some(_)) => bail!("nullable {other:?} not supported (field {})", f.name),
    };
    Ok(code)
}

/// For nullable scalar-ish fields: error when null in a non-nullable version,
/// then run `write` (which handles both Some and None wire forms).
fn null_guard(schema_name: &str, path: &str, nullable: &str, write: String) -> String {
    if nullable == "true" {
        write
    } else {
        format!(
            "if {path}.is_none() && !({nullable}) {{\n    return Err(EncodeError::NullField({schema_name:?}));\n}}\n{write}"
        )
    }
}

fn encode_element(msg: &Message, f: &Field, elem: &FieldType) -> Result<String> {
    let flex = field_flex_expr(msg, f);
    Ok(match elem {
        FieldType::Bool => "buf.put_u8(u8::from(*item));".into(),
        FieldType::Int8 => "buf.put_i8(*item);".into(),
        FieldType::Int16 => "buf.put_i16(*item);".into(),
        FieldType::Uint16 => "buf.put_u16(*item);".into(),
        FieldType::Int32 => "buf.put_i32(*item);".into(),
        FieldType::Uint32 => "buf.put_u32(*item);".into(),
        FieldType::Int64 => "buf.put_i64(*item);".into(),
        FieldType::Float64 => "buf.put_f64(*item);".into(),
        FieldType::Uuid => "wire::put_uuid(buf, *item);".into(),
        FieldType::Struct(_) => "item.encode(buf, version)?;".into(),
        FieldType::String => flex_switch(
            &flex,
            "wire::put_compact_string(buf, item);".into(),
            "wire::put_string(buf, item)?;".into(),
        ),
        FieldType::Bytes => flex_switch(
            &flex,
            "wire::put_compact_bytes(buf, item);".into(),
            "wire::put_bytes(buf, item)?;".into(),
        ),
        other => bail!(
            "array element type {other:?} not supported (field {})",
            f.name
        ),
    })
}

// --- decode ------------------------------------------------------------------

fn decode_field(msg: &Message, f: &Field) -> Result<String> {
    let name = rust_field_name(&f.name);
    let value = decode_value(msg, f)?;
    Ok(format!("this.{name} = {value};"))
}

/// The expression decoding `f`'s value from the free variable `buf`.
fn decode_value(msg: &Message, f: &Field) -> Result<String> {
    let flex = field_flex_expr(msg, f);
    // Folded over the versions the field is actually on the wire, so
    // a guard that can never fire is not emitted at all.
    let nullable_expr = f.nullable.map(|r| r.expr(msg.valid.intersect(f.versions)));

    let value = match (&f.ftype, &nullable_expr) {
        (FieldType::Bool, None) => "wire::get_bool(buf)?".to_string(),
        (FieldType::Int8, None) => "wire::get_i8(buf)?".to_string(),
        (FieldType::Int16, None) => "wire::get_i16(buf)?".to_string(),
        (FieldType::Uint16, None) => "wire::get_u16(buf)?".to_string(),
        (FieldType::Int32, None) => "wire::get_i32(buf)?".to_string(),
        (FieldType::Uint32, None) => "wire::get_u32(buf)?".to_string(),
        (FieldType::Int64, None) => "wire::get_i64(buf)?".to_string(),
        (FieldType::Float64, None) => "wire::get_f64(buf)?".to_string(),
        (FieldType::Uuid, None) => "wire::get_uuid(buf)?".to_string(),
        (FieldType::Struct(n), None) => format!("{n}::decode_with_budget(buf, version, budget)?"),
        (FieldType::Struct(n), Some(nullable)) => {
            let none_val = if nullable == "true" {
                "None".to_string()
            } else {
                format!(
                    "{{\n    if !({nullable}) {{\n        return Err(DecodeError::InvalidLength(-1));\n    }}\n    None\n}}"
                )
            };
            format!(
                "if wire::get_i8(buf)? < 0 {{\n    {none_val}\n}} else {{\n    Some({n}::decode_with_budget(buf, version, budget)?)\n}}"
            )
        }
        (FieldType::String, None) => flex_switch(
            &flex,
            "wire::get_compact_string(buf)?".into(),
            "wire::get_string(buf)?".into(),
        ),
        (FieldType::Bytes | FieldType::Records, None) => {
            let read = flex_switch(
                &flex,
                "wire::get_compact_nullable_bytes(buf)?".into(),
                "wire::get_nullable_bytes(buf)?".into(),
            );
            format!(
                "{{\n    let raw = {read};\n    match raw {{\n        Some(v) => v,\n        None => return Err(DecodeError::InvalidLength(-1)),\n    }}\n}}"
            )
        }
        (FieldType::String, Some(nullable)) => {
            let read = flex_switch(
                &flex,
                "wire::get_compact_nullable_string(buf)?".into(),
                "wire::get_nullable_string(buf)?".into(),
            );
            nullable_check(&read, nullable)
        }
        (FieldType::Bytes | FieldType::Records, Some(nullable)) => {
            let read = flex_switch(
                &flex,
                "wire::get_compact_nullable_bytes(buf)?".into(),
                "wire::get_nullable_bytes(buf)?".into(),
            );
            nullable_check(&read, nullable)
        }
        (FieldType::Array(elem), nullable) => {
            let read_len = flex_switch(
                &flex,
                "wire::get_compact_array_len(buf)?".into(),
                "wire::get_array_len(buf)?".into(),
            );
            // `n` is a wire count and never sizes the allocation: the
            // vector grows from the elements that actually arrive, and
            // every growth is charged to the shared budget first. A
            // struct element also has to consume input — a zero-width
            // element would turn a hostile count into a spin.
            let push = match &**elem {
                FieldType::Struct(_) => {
                    let decode = decode_element(msg, f, elem)?;
                    format!(
                        "let mark = buf.remaining();\n                let item = {decode};\n                budget.progress(mark, buf.remaining())?;\n                budget.push(&mut items, item)?;"
                    )
                }
                // Every primitive codec consumes at least one byte, so
                // progress needs no check here.
                _ => {
                    let decode = decode_element(msg, f, elem)?;
                    format!("budget.push(&mut items, {decode})?;")
                }
            };
            let some_arm = format!(
                "Some(n) => {{\n            let mut items = Vec::new();\n            for _ in 0..n {{\n                {push}\n            }}\n            {}\n        }}",
                if nullable.is_some() {
                    "Some(items)"
                } else {
                    "items"
                }
            );
            let none_arm = match nullable {
                None => "None => return Err(DecodeError::InvalidLength(-1)),".to_string(),
                Some(cond) if cond == "true" => "None => None,".to_string(),
                Some(cond) => format!(
                    "None => {{\n            if !({cond}) {{\n                return Err(DecodeError::InvalidLength(-1));\n            }}\n            None\n        }}"
                ),
            };
            format!(
                "{{\n    let len = {read_len};\n    match len {{\n        {none_arm}\n        {some_arm}\n    }}\n}}"
            )
        }
        (other, Some(_)) => bail!("nullable {other:?} not supported (field {})", f.name),
    };
    Ok(value)
}

/// Wrap a nullable read with a strictness check: null is only legal in
/// versions where the schema allows it.
fn nullable_check(read: &str, nullable: &str) -> String {
    if nullable == "true" {
        read.to_string()
    } else {
        format!(
            "{{\n    let raw = {read};\n    if raw.is_none() && !({nullable}) {{\n        return Err(DecodeError::InvalidLength(-1));\n    }}\n    raw\n}}"
        )
    }
}

fn decode_element(msg: &Message, f: &Field, elem: &FieldType) -> Result<String> {
    let flex = field_flex_expr(msg, f);
    Ok(match elem {
        FieldType::Bool => "wire::get_bool(buf)?".into(),
        FieldType::Int8 => "wire::get_i8(buf)?".into(),
        FieldType::Int16 => "wire::get_i16(buf)?".into(),
        FieldType::Uint16 => "wire::get_u16(buf)?".into(),
        FieldType::Int32 => "wire::get_i32(buf)?".into(),
        FieldType::Uint32 => "wire::get_u32(buf)?".into(),
        FieldType::Int64 => "wire::get_i64(buf)?".into(),
        FieldType::Float64 => "wire::get_f64(buf)?".into(),
        FieldType::Uuid => "wire::get_uuid(buf)?".into(),
        FieldType::Struct(n) => format!("{n}::decode_with_budget(buf, version, budget)?"),
        FieldType::String => flex_switch(
            &flex,
            "wire::get_compact_string(buf)?".into(),
            "wire::get_string(buf)?".into(),
        ),
        other => bail!(
            "array element type {other:?} not supported (field {})",
            f.name
        ),
    })
}
