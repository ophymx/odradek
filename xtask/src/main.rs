//! Workspace automation.
//!
//! `cargo xtask codegen` regenerates `odradek-protocol/src/messages/` from
//! the Kafka message schemas vendored in `odradek-protocol/schemas/`.
//! Output is rustfmt-formatted (so it matches what the repo commits) and
//! written only where it differs, leaving a no-op run with nothing to
//! rebuild.
//!
//! `cargo xtask conformance` runs the acceptance suite against real broker
//! implementations in Docker; see `conformance.rs`.
//!
//! Tagged fields are materialized as `Option` struct fields (`None` =
//! absent on the wire); unknown tags round-trip raw. One shape is not
//! supported (the generator fails loudly on it): fields that are
//! wire-encoded in some versions and tagged in others.
//!
//! Every emitted array loop grows its vector against a shared
//! `budget::Budget` and refuses an element that consumed no input. The
//! bound belongs here rather than in each of the ~36 modules: a wire
//! count is attacker-controlled everywhere it appears, and a hand-added
//! `Vec::with_capacity(n)` in one generated file would undo it.

use std::fmt::Write as _;
use std::fs;
use std::io::Write as _;
use std::path::{Path, PathBuf};
use std::process::{Command, Stdio};

use anyhow::{Context, Result, bail};
use serde_json::Value;

mod conformance;

fn main() -> Result<()> {
    let args: Vec<String> = std::env::args().skip(1).collect();
    let task = args.first().map(String::as_str).unwrap_or_default();
    match task {
        "codegen" => codegen(),
        "conformance" => conformance::conformance(&args[1..]),
        other => bail!("unknown task {other:?}; available tasks: codegen, conformance"),
    }
}

fn workspace_root() -> PathBuf {
    Path::new(env!("CARGO_MANIFEST_DIR"))
        .parent()
        .unwrap()
        .to_path_buf()
}

fn codegen() -> Result<()> {
    let root = workspace_root();
    let schema_dir = root.join("crates/odradek-protocol/schemas");
    let out_dir = root.join("crates/odradek-protocol/src/messages");
    fs::create_dir_all(&out_dir)?;

    let mut schema_files: Vec<PathBuf> = fs::read_dir(&schema_dir)?
        .filter_map(|e| e.ok().map(|e| e.path()))
        .filter(|p| p.extension().is_some_and(|e| e == "json"))
        .collect();
    schema_files.sort();

    let mut messages = Vec::new();
    for path in &schema_files {
        let msg = parse_message(path).with_context(|| format!("parsing {}", path.display()))?;
        messages.push(msg);
    }

    let mut mod_rs = String::new();
    let _ = writeln!(
        mod_rs,
        "//! Kafka message types generated from the vendored schemas.\n\
         //!\n\
         //! @generated by `cargo xtask codegen`. Do not edit by hand; edit the\n\
         //! schemas or the generator and re-run.\n"
    );

    // Generating is cheap and formatting is not, so format the modules in
    // parallel; the result is what gets compared against what is already
    // on disk.
    let mut generated = Vec::new();
    for msg in &messages {
        let module = snake_case(&msg.name);
        let code = generate_message(msg).with_context(|| format!("generating {}", msg.name))?;
        generated.push((module, msg, code));
    }
    let formatted: Vec<String> = std::thread::scope(|scope| {
        let workers: Vec<_> = generated
            .iter()
            .map(|(_, _, code)| scope.spawn(move || rustfmt_or(code)))
            .collect();
        workers
            .into_iter()
            .zip(&generated)
            .map(|(worker, (_, _, code))| worker.join().unwrap_or_else(|_| code.clone()))
            .collect()
    });

    let mut rewritten = 0usize;
    let mut module_names = Vec::new();
    for ((module, msg, _), code) in generated.iter().zip(&formatted) {
        rewritten += usize::from(write_if_changed(
            &out_dir.join(format!("{module}.rs")),
            code,
        )?);
        module_names.push((module.clone(), *msg));
    }

    for (module, _) in &module_names {
        let _ = writeln!(mod_rs, "pub mod {module};");
    }
    let _ = writeln!(mod_rs);
    for (module, msg) in &module_names {
        let _ = writeln!(mod_rs, "pub use {module}::{};", msg.name);
    }

    // Flexibility lookup for requests, used to derive header versions.
    let _ = writeln!(
        mod_rs,
        "\n/// Whether `api_version` of the request identified by `api_key` uses the\n\
         /// flexible (compact) encoding. `None` when the api key has no generated\n\
         /// message type in this crate.\n\
         pub fn request_is_flexible(api_key: i16, api_version: i16) -> Option<bool> {{\n    match api_key {{"
    );
    for (module, msg) in &module_names {
        if msg.typ == "request" {
            let key = msg.api_key.expect("request without apiKey");
            let _ = writeln!(
                mod_rs,
                "        {key} => Some({module}::is_flexible(api_version)),"
            );
        }
    }
    let _ = writeln!(mod_rs, "        _ => None,\n    }}\n}}");

    let _ = writeln!(
        mod_rs,
        "\n/// The version range this schema snapshot speaks for `api_key`'s\n\
         /// request type, or `None` for keys with no generated support.\n\
         pub fn supported_versions(api_key: i16) -> Option<(i16, i16)> {{\n    match api_key {{"
    );
    for (_module, msg) in &module_names {
        if msg.typ == "request" {
            let key = msg.api_key.expect("request without apiKey");
            let _ = writeln!(
                mod_rs,
                "        {key} => Some(({}, {})),",
                msg.valid.min, msg.valid.max
            );
        }
    }
    let _ = writeln!(mod_rs, "        _ => None,\n    }}\n}}");

    rewritten += usize::from(write_if_changed(
        &out_dir.join("mod.rs"),
        &rustfmt_or(&mod_rs),
    )?);
    println!(
        "generated {} message modules in {} ({rewritten} file(s) changed)",
        module_names.len(),
        out_dir.display()
    );
    Ok(())
}

/// Write `contents` only if the file does not already say exactly that.
///
/// Rewriting a byte-identical file still bumps its mtime, and a bumped
/// mtime under `src/messages/` makes cargo rebuild the protocol crate and
/// everything downstream — six seconds of compiling to reach the state it
/// was already in. Returns whether the file changed.
fn write_if_changed(path: &Path, contents: &str) -> Result<bool> {
    if fs::read_to_string(path).is_ok_and(|on_disk| on_disk == contents) {
        return Ok(false);
    }
    fs::write(path, contents).with_context(|| format!("writing {}", path.display()))?;
    Ok(true)
}

/// Format generated code as `cargo fmt` would.
///
/// The generator emits legible-enough but unformatted Rust, while what is
/// committed is formatted — so without this every file would differ from
/// its own last output and [`write_if_changed`] could never skip a write.
/// Returns an empty string if rustfmt is unavailable or unhappy; callers
/// then keep the unformatted source, and `cargo fmt` (which CI runs right
/// after codegen anyway) settles the final shape.
fn rustfmt(code: &str) -> String {
    let Ok(mut child) = Command::new("rustfmt")
        .args(["--edition", "2024", "--emit", "stdout"])
        .stdin(Stdio::piped())
        .stdout(Stdio::piped())
        .stderr(Stdio::null())
        .spawn()
    else {
        return String::new();
    };
    // rustfmt parses the whole input before emitting anything, so writing
    // it all and then reading cannot deadlock on a full pipe.
    let Some(mut stdin) = child.stdin.take() else {
        return String::new();
    };
    let written = stdin
        .write_all(code.as_bytes())
        .and_then(|()| stdin.flush());
    drop(stdin);
    match (written, child.wait_with_output()) {
        (Ok(()), Ok(out)) if out.status.success() => {
            String::from_utf8(out.stdout).unwrap_or_default()
        }
        _ => String::new(),
    }
}

/// [`rustfmt`], falling back to the unformatted source.
fn rustfmt_or(code: &str) -> String {
    let formatted = rustfmt(code);
    if formatted.is_empty() {
        code.to_owned()
    } else {
        formatted
    }
}

